from abc import ABC, abstractmethod
from typing import Callable

class Scheduler(ABC):
    @abstractmethod
    def add_interval(self, name: str, fn: Callable[[], None], *, minutes: int) -> None: ...
    @abstractmethod
    def list_jobs(self) -> list[str]: ...
    @abstractmethod
    def run_now(self, name: str) -> None: ...
    @abstractmethod
    def start(self) -> None: ...
